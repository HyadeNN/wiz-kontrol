def detect_language():
    """Windows arayüz dilini döndürür; desteklenmiyorsa İngilizce."""
    try:
        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
    except (AttributeError, OSError):
        return "en"
    return _WIN_LANG.get(langid & 0x3FF, "en")


